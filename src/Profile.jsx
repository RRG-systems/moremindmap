  async function handleStartAssessment() {
    // If promo is active, skip checkout and enter Page 0A
    if (promoValidated) {
      console.log("[PROMO PATH] Promo validated, entering Page 0A")
      // Page 0A will show because page0AComplete is false
      // User must complete Page 0A before assessment starts
      return
    }

    // Otherwise, redirect to Stripe checkout
    if (!selectedOffer) {
      console.log("[ERROR] No selectedOffer but button was enabled?")
      return
    }

    console.log("[CHECKOUT PATH] Redirecting to Stripe with offer:", selectedOffer)
    setCheckoutLoading(true)
    setCheckoutError("")
    try {
      await startStripeCheckout({
        product_key: "behavior_operating_system",
        email: email.trim(),
        source_context: "behavior_operating_system_profile"
      }, { idempotencyKey: checkoutIdempotencyKey })
    } catch {
      setCheckoutError("Payment setup is not available yet. Please try again shortly.")
      setCheckoutLoading(false)
    }
  }

  function goNext() {
    console.log("BUTTON CLICKED — goNext() called")
    console.log("STEP:", step)
    console.log("TOTAL QUESTIONS:", questions.length)
    if (!currentAnswer) {
      console.log("BLOCKED: currentAnswer is falsy")
      return
    }
    
    if (step < questions.length - 1) {
      console.log("NOT FINAL STEP — advancing to next question")
      const nextStep = step + 1
      setStep(nextStep)
      void persistDraft({ phase: 'ASSESSMENT', nextStep })
    } else {
      console.log("FINAL STEP — CALLING submitAssessment()")
      submitAssessment()
    }
  }

  function goBack() {
    if (step > 0) {
      const nextStep = step - 1
      setStep(nextStep)
      void persistDraft({ phase: 'ASSESSMENT', nextStep })
    }
  }

